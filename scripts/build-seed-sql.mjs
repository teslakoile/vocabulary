// Turns the validated corpus into idempotent seed SQL.
// Usage: node scripts/build-seed-sql.mjs > .scratch/vocab-pwa/corpus/seed.sql
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const RAW_DIR = '.scratch/vocab-pwa/corpus/raw';
const SOURCE = '.scratch/vocab-pwa/source-list.md';
// Easiest first, because this is also the order cards enter intake.
const TYPES = ['recognition', 'identify', 'reverse', 'production'];
// 3: plain definitions and word_distractors. 4: glosses and plain cautions.
const PROMPT_VERSION = 4;
const NOW = process.env.SEED_NOW || new Date().toISOString();

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => q(JSON.stringify(v ?? []));
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 48);

// Kyle's original order is the intake order, so read the source list for position.
const order = readFileSync(SOURCE, 'utf8').split('\n').slice(1).map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const positionOf = new Map(order.map((h, i) => [h, i]));

const files = existsSync(RAW_DIR) ? readdirSync(RAW_DIR).filter((f) => f.endsWith('.json')) : [];
const entries = files
  .map((f) => JSON.parse(readFileSync(join(RAW_DIR, f), 'utf8')))
  .filter((e) => positionOf.has(e.headword))
  .sort((a, b) => positionOf.get(a.headword) - positionOf.get(b.headword));

const ids = new Set();
const out = [];
out.push('-- Generated by scripts/build-seed-sql.mjs. Re-runnable: entry and sense content is');
out.push('-- overwritten, and card rows keep their schedule and history: only intake_order is rewritten.');
out.push('--');
out.push('-- No BEGIN/COMMIT: remote D1 rejects SQL transaction statements. Not needed here,');
out.push('-- because every statement is an upsert, so a half-applied run is fixed by rerunning.');

let intake = 0;
let senseCount = 0;
let cardCount = 0;

for (const entry of entries) {
  const eid = `e_${slug(entry.headword)}`;
  if (ids.has(eid)) throw new Error(`id collision on ${eid} (${entry.headword})`);
  ids.add(eid);

  out.push(
    `INSERT INTO entries (id, headword, capture_note, tags, status, created_at, updated_at) VALUES ` +
      `(${q(eid)}, ${q(entry.headword)}, NULL, ${j(entry.tags)}, 'ready', ${q(NOW)}, ${q(NOW)}) ` +
      `ON CONFLICT(id) DO UPDATE SET headword=excluded.headword, tags=excluded.tags, status='ready', updated_at=excluded.updated_at;`
  );

  entry.senses.forEach((s, i) => {
    const sid = `s_${slug(entry.headword)}_${i}`;
    senseCount++;
    out.push(
      `INSERT INTO senses (id, entry_id, position, term, accepted, definition, caution, example, cues, distractors, word_distractors, gloss, gloss_distractors, prompt_version, created_at, updated_at) VALUES ` +
        `(${q(sid)}, ${q(eid)}, ${i}, ${q(s.term)}, ${j(s.accepted)}, ${q(s.definition)}, ${q(s.caution)}, ${q(s.example)}, ${j(s.cues)}, ${j(s.distractors)}, ${j(s.word_distractors)}, ${q(s.gloss ?? '')}, ${j(s.gloss_distractors)}, ${PROMPT_VERSION}, ${q(NOW)}, ${q(NOW)}) ` +
        `ON CONFLICT(id) DO UPDATE SET term=excluded.term, accepted=excluded.accepted, definition=excluded.definition, ` +
        `caution=excluded.caution, example=excluded.example, cues=excluded.cues, distractors=excluded.distractors, ` +
        `word_distractors=excluded.word_distractors, gloss=excluded.gloss, gloss_distractors=excluded.gloss_distractors, ` +
        `prompt_version=excluded.prompt_version, updated_at=excluded.updated_at;`
    );

    // Cards start unseen: no fsrs_state, no due_at. intake_log lets them in, 6 a day.
    for (const type of TYPES) {
      cardCount++;
      out.push(
        `INSERT INTO cards (id, sense_id, type, fsrs_state, due_at, intake_order, created_at) VALUES ` +
          `(${q(`c_${slug(entry.headword)}_${i}_${type}`)}, ${q(sid)}, '${type}', NULL, NULL, ${intake++}, ${q(NOW)}) ` +
          // intake_order is the only card column this rewrites. Adding a card
          // type renumbers the whole sequence, and a card left on the old
          // numbering drifts away from its own siblings. fsrs_state, due_at and
          // last_event_at are never touched, so schedules and history survive.
          `ON CONFLICT(id) DO UPDATE SET intake_order = excluded.intake_order;`
      );
    }
  });
}

// Never touches push_subscription: reseeding must not unsubscribe the phone.
out.push(
  `INSERT INTO settings (id, timezone, nudge_hour, new_cards_per_day, updated_at) VALUES (1, 'Asia/Manila', 13, 6, ${q(NOW)}) ` +
    `ON CONFLICT(id) DO UPDATE SET timezone=excluded.timezone, nudge_hour=excluded.nudge_hour, ` +
    `new_cards_per_day=excluded.new_cards_per_day, updated_at=excluded.updated_at;`
);
out.push(`-- ${entries.length} entries, ${senseCount} senses, ${cardCount} cards, ${Math.ceil(cardCount / 6)} days of intake`);

console.log(out.join('\n'));
console.error(`${entries.length} entries → ${senseCount} senses → ${cardCount} cards → ${Math.ceil(cardCount / 6)} days of intake`);
